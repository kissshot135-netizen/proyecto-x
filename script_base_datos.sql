-- Script de creación de Base de Datos para SGAP
-- Ejecutar en Oracle SQL Developer

CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR2(100) UNIQUE NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    rol VARCHAR2(20) NOT NULL,
    password_hash VARCHAR2(512) NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE solicitudes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id NUMBER NOT NULL,
    procedimiento VARCHAR2(100),
    descripcion VARCHAR2(500),
    estado VARCHAR2(20) DEFAULT 'Pendiente' NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    actualizada TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resuelta_por VARCHAR2(100),
    CONSTRAINT fk_solicitante FOREIGN KEY (solicitante_id) REFERENCES usuarios(id)
);

CREATE TABLE historial (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    accion VARCHAR2(100) NOT NULL,
    referencia VARCHAR2(100),
    detalle VARCHAR2(500)
);

CREATE TABLE procedimientos (
    nombre VARCHAR2(100) PRIMARY KEY,
    activo NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE campos_procedimiento (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedimiento_nombre VARCHAR2(100) NOT NULL,
    campo VARCHAR2(100) NOT NULL,
    CONSTRAINT fk_proc_nombre FOREIGN KEY (procedimiento_nombre) REFERENCES procedimientos(nombre) ON DELETE CASCADE
);

